def _caminho_sqlite_padrao() -> Path:
    import sqlite3

    padrao = BASE_DIR / 'db.sqlite3'
    try:
        with sqlite3.connect(padrao) as conn:
            conn.execute("SELECT 1")
        return padrao
    except Exception:
        return BASE_DIR / 'sentinela.sqlite3'


